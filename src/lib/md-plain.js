// Markdown из описаний PR → обычный текст для задач в админке (там текст показывается как есть, без разметки)
export function mdPlain(text) {
  return String(text || "")
    .replace(/\r/g, "")
    .replace(/^#{1,6}\s+/gm, "")                        // заголовки
    .replace(/^(\s*)[-*+]\s+/gm, "$1• ")                 // пункты списка
    .replace(/\*\*(.+?)\*\*|__(.+?)__/g, "$1$2")         // жирный
    .replace(/(^|[^*\w])\*(?!\s)([^*\n]+?)\*(?!\w)/g, "$1$2") // курсив
    .replace(/`([^`\n]+)`/g, "$1")                       // код в строке
    .replace(/^```.*$/gm, "")                            // блоки кода
    .replace(/!?\[([^\]]+)\]\((?:[^)]+)\)/g, "$1")       // ссылки и картинки
    .replace(/^>\s?/gm, "")                              // цитаты
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
