export function evaluationPrompt(pat, facts) {
  const questions = facts.doctorMessages.length
    ? facts.doctorMessages.slice(-20).map((t, i) => `${i + 1}. ${t}`).join("\n")
    : "не задал ни одного вопроса";
  const referral = facts.referrals.length ? `; направление — ${facts.referrals.join(", ")}` : "";
  return {
    maxTokens: 1100,
    temperature: 0.2,
    prompt: `Ты — профессор (${pat.specialization}), 25 лет клинического стажа. Разбери приём ${facts.profession ? `врача (${facts.profession})` : "ординатора"} прямо и конкретно, как коллега.
Пациент: ${patientCard(pat)}. ИСТИННЫЙ ДИАГНОЗ: ${pat.true_diagnosis}.
Вопросы врача:
${questions}
Действия: обследования — ${facts.tests.join(", ") || "нет"}; осмотр — ${facts.physicals.join(", ") || "нет"}; диагноз — ${facts.diagnosis || "не поставлен"}; лечение и рекомендации — ${facts.treatment || "не назначено"}${referral}${facts.discharged ? "; врач отказался от пациента" : ""}.${facts.hints?.length ? `\nВрач брал подсказки (${facts.hints.length} из 3): ${facts.hints.map((h) => `«${h}»`).join("; ")}. То, что сделано по подсказке, — заслуга подсказки, а не врача: учитывай это в осях.` : ""}
Оцени три оси целыми числами 0-5 по якорям (итоговую оценку посчитает система по формуле — её не ставь):
- diagnosis — диагностический процесс и итог: 5 — ключевые вопросы заданы, нужный осмотр и обследования сделаны, диагноз верный и полный; 4 — диагноз верный, но пропущено одно важное звено обследования или диагноз неполный; 3 — диагноз частично верный (верный синдром или орган, но не нозология) либо верный, но поставлен почти наугад; 2 — диагноз неверный, но диагностический поиск шёл в разумную сторону; 1 — неверный диагноз при хаотичном поиске; 0 — диагноза нет.
- treatment — лечение и тактика: 5 — по клиническим рекомендациям, с дозами или режимом и планом наблюдения; 4 — верно по сути, без деталей; 3 — частично верно или только симптоматически; 2 — неэффективно; 1 — потенциально вредно; 0 — не назначено. Обоснованное направление к профильному специалисту с первичными рекомендациями — это 4-5, лечение за специалиста не требуется. Направление к неподходящему специалисту — 1-2.
- communication — 5 — представился, открытые вопросы, уточнял детали, объяснил пациенту диагноз и план; 3 — вопросы по делу, но сухо или без объяснений; 1 — грубо, закрытыми вопросами или почти без вопросов.
Сравнивай поставленный диагноз с истинным по смыслу, синонимы и близкие формулировки считаются верными. diagnosis_correct: yes — та же нозология; partial — верный синдром, орган или группа болезней; no — другое; none — диагноз не поставлен.
critical_error — пустая строка или коротко: пропущено состояние, угрожающее жизни, или назначено то, что может навредить.
Оценивай только то, что врач реально сделал по списку выше, не додумывай. Не снижай за краткость, если ключевое спрошено. Будь последовательным: одинаковый приём — одинаковые баллы.
Верни JSON:
{"axes":{"diagnosis":0-5,"communication":0-5,"treatment":0-5},"diagnosis_correct":"yes|partial|no|none","critical_error":"","mkb10":"код МКБ-10 истинного диагноза","expert_text":"разбор, 4-6 предложений: что сделано хорошо, какие ключевые вопросы, осмотр или обследования пропущены и почему они важны именно при этом диагнозе, где рассуждение ушло в сторону","dialog_moments":[{"quote":"цитата врача","comment":"что было хорошо/плохо"}],"strengths":["короткая сильная сторона"],"weaknesses":["короткий пробел в знаниях"],"recommendation":"один конкретный совет на будущее: что делать при такой жалобе в следующий раз","outcome_update":"improving|stable|worsening|critical","post_story":"что стало с пациентом через 2-4 недели, 2-3 конкретных предложения, исход логично следует из верности диагноза и лечения"}
dialog_moments — не больше 2, strengths и weaknesses — не больше 3.`,
  };
}

export function quizPrompt(pat, topics, guide = null, krName = "") {
  const g = guide || {};
  const tx = (g.treatment || []).map((t) => `${t.drug}: ${t.dose}${t.duration ? `, ${t.duration}` : ""}`).join("; ");
  const dx = (g.tests || []).map((t) => t.name).join(", ");
  return {
    maxTokens: 2000,
    temperature: 0.4,
    prompt: `Составь клинический тест «работа над ошибками» из 5 вопросов, чтобы врач запомнил, как по российским клиническим рекомендациям диагностируют и лечат этот случай.
Случай: ${pat.true_diagnosis} (${pat.specialization}), пациент ${patientCard(pat)}.
${krName ? `Опора — клинические рекомендации Минздрава России «${krName}».` : "Опора — действующие клинические рекомендации Минздрава России."}
${dx ? `Диагностика по КР: ${dx}.\n` : ""}${tx ? `Лечение по КР: ${tx}.\n` : ""}Пробелы врача на приёме: ${topics.join("; ")}.
Состав: 2 вопроса по лечению (препарат выбора, доза и кратность, длительность курса, чем заменить при непереносимости), 2 — по диагностике (метод выбора, критерий диагноза, что обязательно спросить или проверить), 1 — по главной ошибке врача на этом приёме. Вопросы — клинические задачи, а не определения из учебника.
Правила: у каждого вопроса ровно один верный ответ; 3 остальных — правдоподобные, клинически обоснованные, но неверные; без «всё перечисленное»; варианты по 2-8 слов; дозы и названия — как в российских КР (МНН).
explanation — 2-4 предложения: почему верный ответ верен со ссылкой на КР («по КР …»), чем опасен или хуже самый частый неверный вариант, что запомнить.
JSON: {"questions":[{"text":"вопрос","options":["A","B","C","D"],"correct":индекс 0-3,"topic":"treatment|diagnostics|error","explanation":"…"}]}`,
  };
}

