// Промпты. Пишем коротко: каждое слово промпта — это входные токены на каждом вызове.
import { HISTORY_WINDOW, PEDIATRIC_SPECS } from "../config.js";
import { pick } from "./util.js";

const SEEDS = [
  "живёт в деревне, работает физически",
  "офисный работник, сидячий образ жизни",
  "спортсмен-любитель",
  "пенсионер с сопутствующими заболеваниями",
  "молодой, без хронических заболеваний",
  "медработник, хорошо знает симптомы",
  "тревожный, склонен к ипохондрии",
  "отрицает болезнь, затянул с визитом",
  "приехал из другого города, наблюдался у другого врача",
  "курильщик со стажем 20+ лет",
];

const COMPLEXITY = {
  easy: "типичный хрестоматийный случай, классические симптомы",
  medium: "нетипичное начало, один отвлекающий фактор",
  medium_hard: "маскирующиеся симптомы, два конкурирующих диагноза",
  hard: "редкая патология, противоречивые данные",
};

export function patientPrompt({ spec, profession, complexity, usedDiagnoses, isAlien }) {
  if (isAlien) {
    return {
      maxTokens: 700,
      prompt: `Создай пациента-ИНОПЛАНЕТЯНИНА для медицинского симулятора: абсурдно, но внутренне логично, с юмором.
JSON:
{"name":"труднопроизносимое имя","age":"возраст по-инопланетному, строкой","sex":"неизвестен","chief_complaint":"жалоба на орган, которого у людей нет","true_diagnosis":"выдуманная болезнь с псевдолатинским названием","full_history":"история болезни, 3-5 предложений","personality":"манера речи","condition_trajectory":"stable","opening_phrase":"странная дружелюбная первая фраза","findings":{"exam":"абсурдный признак при осмотре","lab":"абсурдный анализ","imaging":"абсурдная визуализация","ecg":"абсурдная ЭКГ","pathology":""}}`,
    };
  }
  const pediatric = PEDIATRIC_SPECS.includes(spec) || /педиатр|неонат|детск|новорожд|подрост/i.test(`${profession} ${spec}`);
  const ages = pickAgeRange(pediatric);
  const sex = pick(["male", "female"]);
  const used = usedDiagnoses.length ? `\nНе повторяй диагнозы: ${usedDiagnoses.slice(-15).join("; ")}.` : "";
  return {
    maxTokens: 1000,
    prompt: `Создай уникального реалистичного пациента для тренировки врача.
Врач: ${profession || spec}, раздел: ${spec}. Диагноз строго из этого раздела.
Сложность: ${COMPLEXITY[complexity] || COMPLEXITY.medium}.
Пол: ${sex === "male" ? "мужской" : "женский"}${pediatric ? " (ребёнок)" : ""}, возраст ${ages[0]}–${ages[1]} лет, фон: ${pick(SEEDS)}.
Русские имя и фамилия, редкие.${used}
JSON:
{"name":"Имя Фамилия","age":число,"sex":"${sex}","chief_complaint":"с чем пришёл, живым языком","true_diagnosis":"точный диагноз со стадией","full_history":"анамнез, образ жизни, привычки, ВСЕ симптомы, включая те, что пациент сам не назовёт — 4-7 предложений","personality":"характер и манера речи","condition_trajectory":"improving|stable|worsening","opening_phrase":"первая фраза пациента в кабинете, разговорная","findings":{"exam":"что врач обнаружит при физикальном осмотре (осмотр, пальпация, перкуссия, аускультация, АД и пульс) — только то, что можно увидеть, нащупать или услышать","lab":"изменения в анализах крови и мочи, с цифрами","imaging":"что покажут УЗИ, КТ, МРТ, рентген, эндоскопия — с указанием метода и размеров","ecg":"ЭКГ; если изменений нет — «норма»","pathology":"гистология или цитология; если не применимо — пусто"}}`,
  };
}

function pickAgeRange(pediatric) {
  return pick(pediatric ? [[0, 3], [4, 10], [11, 17]] : [[18, 30], [31, 45], [46, 60], [61, 75], [76, 90]]);
}

function patientCard(pat) {
  const age = pat.is_alien ? pat.age : `${pat.age} лет`;
  const sex = pat.sex === "female" ? "женщина" : pat.sex === "male" ? "мужчина" : pat.sex || "";
  return `${pat.name}, ${age}${sex ? ", " + sex : ""}`;
}

/** Системный промпт роли пациента — один на весь диалог */
export function patientSystem(pat) {
  return `Ты — пациент на приёме у врача. Никогда не выходи из роли.
Ты: ${patientCard(pat)}. Характер: ${pat.personality}.
Твоё состояние (ты его чувствуешь, но диагноза не знаешь): ${pat.full_history}
${pat.is_alien ? "Ты инопланетянин: говоришь странно, иногда не понимаешь человеческих вопросов.\n" : ""}Правила: ты не врач и не знаешь терминов; отвечай только на заданный вопрос, не выкладывай всё сразу; на грубость реагируй эмоционально, на внимание — доверием; 1-3 коротких предложения разговорным языком, только по-русски; без имени и ремарок в скобках.`;
}

export function historyForAi(history) {
  const summary = history.filter((m) => m.role === "summary").map((m) => m.text).join(" ");
  const msgs = history.filter((m) => m.role === "doctor" || m.role === "patient").slice(-HISTORY_WINDOW);
  const lines = msgs.map((m) => `${m.role === "doctor" ? "Врач" : "Пациент"}: ${m.text}`);
  return (summary ? `[Ранее: ${summary}]\n` : "") + lines.join("\n");
}

export function patientReplyPrompt(pat, doctorMessage) {
  // Последняя реплика врача уже в истории — не дублируем её
  const history = historyForAi(pat.conversation_history.slice(0, -1));
  return {
    system: patientSystem(pat),
    maxTokens: 160,
    prompt: `${history ? `Диалог:\n${history}\n\n` : ""}Врач: ${doctorMessage}\nТвой ответ:`,
  };
}

export function farewellPrompt(pat, actions) {
  return {
    system: patientSystem(pat),
    maxTokens: 70,
    prompt: `Врач завершает приём. Его действия: ${actions.join("; ") || "без назначений"}.
Последние реплики:\n${historyForAi(pat.conversation_history).split("\n").slice(-4).join("\n")}
Попрощайся одной-двумя фразами в своём характере:`,
  };
}

// Что вообще может показать метод — чтобы в УЗИ не появлялись анализы крови, а в осмотре кожи — глюкоза
const METHOD_KINDS = [
  { kind: "ecg", re: /экг|электрокардио|холтер|смад/i, scope: "только электрическая активность сердца: ритм, ЧСС, интервалы PQ, QRS, QT, электрическая ось, сегмент ST, зубцы" },
  { kind: "pathology", re: /биопс|гистолог|цитолог|пункци|иммуногисто/i, scope: "только морфология полученного материала: откуда взят, клеточный состав, гистологическая картина" },
  { kind: "imaging", re: /(^|[^а-яё])(кт|мскт|мрт|узи|эхо)([^а-яё]|$)|томограф|рентген|флюорограф|доппл|дуплекс|маммограф|сцинтиграф|пэт|ангиограф|денситометр|эндоскоп|фгдс|эгдс|колоноскоп|бронхоскоп|цистоскоп|лапароскоп|ирригоскоп/i, scope: "только то, что видно этим методом в исследуемой области: размеры, контуры, структура, плотность или эхогенность, очаги и их локализация" },
  { kind: "lab", re: /анализ|кров|моч|кал[аы]?([^а-яё]|$)|маркер|гормон|биохим|посев|пцр|серолог|коагулог|глюкоз|гемоглоб|ттг|антител|мазок|ликвор|липид|электролит|тропонин/i, scope: "только показатели, которые входят в этот анализ, — значения с единицами и нормой в скобках" },
];

export function methodKind(testName) {
  return METHOD_KINDS.find((m) => m.re.test(testName)) || { kind: "other", scope: "только данные, которые реально даёт этот метод" };
}

/** Находки по диагнозу для конкретного метода. Старые пациенты — одна строка на все методы. */
function findingsFor(pat, kind) {
  const f = pat.findings;
  if (f && typeof f === "object") return f[kind] || "изменений, выявляемых этим методом, нет — опиши норму";
  return pat.key_findings ? `${pat.key_findings} (бери отсюда ТОЛЬКО то, что выявляется этим методом)` : "по диагнозу";
}

export function testResultPrompt(pat, testName) {
  const m = methodKind(testName);
  return {
    maxTokens: 420,
    temperature: 0.4,
    prompt: `Напиши протокол обследования «${testName}» как врач-диагност.
Пациент: ${patientCard(pat)}.
Скрытый диагноз (НЕ называй его): ${pat.true_diagnosis}.
Что этот метод выявит у пациента: ${findingsFor(pat, m.kind)}.
${pat.is_alien ? "Пациент — инопланетянин: заключение абсурдное, с пометкой «референсные значения для вида не установлены».\n" : ""}Протокол содержит ${m.scope}.
СТРОГО: никаких данных других методов. В УЗИ, КТ, МРТ нельзя писать анализы крови, ЭКГ, эндоскопию, вес и рост; в анализе крови нельзя писать ЭКГ, визуализацию, осмотр кожи; в ЭКГ — только ЭКГ. Если болезнь этим методом не выявляется — опиши нормальный или неспецифичный результат.
Если область исследования не указана — выбери уместную для жалоб и назови её в первой строке. 6-10 строк, только объективные данные, без диагноза, без имени пациента и без вступлений.`,
  };
}

export function physicalExamPrompt(pat, action) {
  return {
    system: patientSystem(pat),
    maxTokens: 260,
    temperature: 0.5,
    prompt: `Врач выполняет физикальный осмотр: «${action}». Скрытый диагноз: ${pat.true_diagnosis}.
Что врач может найти при осмотре у этого пациента: ${findingsFor(pat, "exam")}.
Опиши ТОЛЬКО то, что врач получает именно этим приёмом — глазами, руками, стетоскопом, тонометром — и только в осматриваемой области. Аускультация лёгких — дыхание и хрипы; осмотр кожи — цвет, влажность, тургор, высыпания; пальпация живота — мягкость, болезненность, органы; давление и пульс — цифры АД и пульса.
Нельзя: результаты анализов, УЗИ, КТ, ЭКГ, эндоскопии; находки из других областей тела; диагноз. Если болезнь в этой области не проявляется — опиши норму. Если это не физикальный осмотр, а обследование — так и скажи в sensation одним предложением.
Верни JSON: {"sensation":"находки врача — профессионально, 2-4 предложения","reaction":"реакция пациента на осмотр — слова или эмоция, 1-2 предложения, в характере"}`,
  };
}

export function evaluationPrompt(pat, facts) {
  const questions = facts.doctorMessages.length
    ? facts.doctorMessages.slice(-20).map((t, i) => `${i + 1}. ${t}`).join("\n")
    : "не задал ни одного вопроса";
  const referral = facts.referrals.length ? `; направление — ${facts.referrals.join(", ")}` : "";
  return {
    maxTokens: 900,
    temperature: 0.4,
    prompt: `Ты — профессор (${pat.specialization}), 25 лет клинического стажа. Разбери приём ${facts.profession ? `врача (${facts.profession})` : "ординатора"} прямо и конкретно, как коллега.
Пациент: ${patientCard(pat)}. ИСТИННЫЙ ДИАГНОЗ: ${pat.true_diagnosis}.
Вопросы врача:
${questions}
Действия: обследования — ${facts.tests.join(", ") || "нет"}; осмотр — ${facts.physicals.join(", ") || "нет"}; диагноз — ${facts.diagnosis || "не поставлен"}; лечение и рекомендации — ${facts.treatment || "не назначено"}${referral}${facts.discharged ? "; врач отказался от пациента" : ""}.
Шкала: верный полный диагноз 4.5-5; частично верный 3.5-4; неверный 1-2.5; меньше 3 вопросов −1; нет осмотра −0.5; нет нужных обследований −0.5.
Направление к специалисту — полноценное завершение приёма: диагноз направления оценивай как диагноз. Если направление к профильному специалисту обосновано, диагноз верный и даны первичные рекомендации — это правильная тактика, ставь 4.5-5 и не снижай ось «лечение» за то, что лечение назначит специалист. Направление к неподходящему специалисту — ошибка тактики.
Верни JSON:
{"rating":0-5 с одним знаком,"axes":{"diagnosis":0-5,"communication":0-5,"treatment":0-5},"diagnosis_correct":"yes|partial|no","expert_text":"разбор, 3-5 предложений","dialog_moments":[{"quote":"цитата врача","comment":"что было хорошо/плохо"}],"strengths":["короткая сильная сторона"],"weaknesses":["короткий пробел в знаниях"],"recommendation":"один совет на будущее","outcome_update":"improving|stable|worsening|critical","post_story":"что стало с пациентом через 2-4 недели, 2-3 конкретных предложения, исход логично следует из оценки"}
dialog_moments — не больше 2, strengths и weaknesses — не больше 3.`,
  };
}

