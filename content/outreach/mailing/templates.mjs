function link(tpl, id) {
  return tpl.replaceAll("{id}", encodeURIComponent(id));
}

/** Первое письмо: { subject, text } */
export function firstLetter(letter, cfg) {
  const [offer, ask] = OFFERS[letter.offer] || OFFERS.event;
  const text = [
    letter.greeting || "Здравствуйте!",
    letter.hook,
    `Меня зовут ${cfg.sender_name}, ${cfg.sender_about}. ${ABOUT}`,
    offer,
    `Посмотреть, как это работает, можно за пару минут без регистрации: ${link(cfg.demo_url, letter.id)}\nПрезентация (PDF, 8 слайдов): ${cfg.pdf_url}`,
    ask,
    ["С уважением,", cfg.sender_name, ...(cfg.signature || [])].join("\n"),
    "P.S. Если тема вам неактуальна, просто ответьте «нет» — больше писать не буду.",
  ].join("\n\n");
  return { subject: letter.subject, text };
}

/** Напоминание в той же переписке: { subject, text } с цитатой первого письма */
export function followUp(letter, cfg, sentAt) {
  const first = firstLetter(letter, cfg);
  const when = new Date(sentAt).toLocaleDateString("ru-RU", { day: "numeric", month: "long", timeZone: "Europe/Moscow" });
  const quote = first.text.split("\n").map((l) => (l ? `> ${l}` : ">")).join("\n");
  const text = [
    letter.greeting || "Здравствуйте!",
    "Возвращаюсь к письму ниже о тренажёре Help me, Doctor — понимаю, что дел много. Если тема неактуальна, просто ответьте «нет». А если интересно, достаточно короткого «да» — пришлю детали.",
    `${cfg.sender_name}`,
    `${when}, ${cfg.from_name || cfg.sender_name} пишет:\n${quote}`,
  ].join("\n\n");
  return { subject: /^re:/i.test(first.subject) ? first.subject : `Re: ${first.subject}`, text };
}
