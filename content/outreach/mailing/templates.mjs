export function appLink(cfg, id) {
  return cfg.app_url.replaceAll("{id}", encodeURIComponent(id));
}

/** Первое письмо: { subject, text } */
export function firstLetter(letter, cfg) {
  const offer = OFFERS[letter.offer] || OFFERS.event;
  const text = [
    letter.greeting || "Здравствуйте!",
    letter.hook,
    `Меня зовут ${cfg.sender_name}, я ${cfg.sender_about}. ${ABOUT}`,
    offer,
    `Открыть тренажёр (регистрация за минуту): ${appLink(cfg, letter.id)}\nКоротко о проекте (PDF): ${cfg.pdf_url}`,
    letter.questions,
    ["С уважением,", cfg.sender_name, ...(cfg.signature || [])].join("\n"),
  ].filter(Boolean).join("\n\n");
  return { subject: letter.subject, text };
}

/** Напоминание в той же переписке — коротко и лично, без рекламы; ниже цитата первого письма */
export function followUp(letter, cfg, sentAt) {
  const first = firstLetter(letter, cfg);
  const when = new Date(sentAt).toLocaleDateString("ru-RU", { day: "numeric", month: "long", timeZone: "Europe/Moscow" });
  const quote = first.text.split("\n").map((l) => (l ? `> ${l}` : ">")).join("\n");
  const name = String(cfg.sender_name).split(" ")[0];
  const text = [
    letter.greeting || "Здравствуйте!",
    `Пишу ещё раз — вдруг моё письмо затерялось среди других. ${letter.questions || "Подскажите, пожалуйста, кому лучше написать по этому вопросу?"}`,
    "Буду благодарна за короткий ответ.",
    name,
    `${when}, ${cfg.from_name || cfg.sender_name} пишет:\n${quote}`,
  ].join("\n\n");
  return { subject: /^re:/i.test(first.subject) ? first.subject : `Re: ${first.subject}`, text };
}
