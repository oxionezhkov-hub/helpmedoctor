/** Подставляет схемы вместо меток <!--fig:имя--> */
export function withFigures(html) {
  return html.replace(/<!--fig:([\w-]+)-->/g, (m, name) => {
    if (!FIGURES[name]) throw new Error(`Нет иллюстрации ${name}`);
    return FIGURES[name];
  });
}
