const steps = (items, cls = "") => `<ol class="fig-steps ${cls}">${items.map(([t, d], i) => `<li><span class="n">${i + 1}</span><b>${t}</b>${d ? `<span>${d}</span>` : ""}</li>`).join("")}</ol>`;
