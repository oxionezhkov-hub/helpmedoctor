// Обороты, которые выдают «машинный» или переводной текст. Общие для блога (test/unit.test.mjs) и канала (scripts/tg-channel.mjs).
// Если оборот попался — не обходите проверку синонимом, перепишите фразу так, как сказали бы вслух однокурснику.

// Шаблоны конвейера из аудита блога 26.09.2026
export const STOP_PHRASES = ["в этой статье", "разберём", "поддаётся алгоритму", "поддаётся системе", "шанс пропустить находку", "ниже — рабочий алгоритм", "удобно разбирать", "от находки к синдрому", "в отрыве от остальной картины", "какие находки вы", "а какие пропустили", "как тренировать навык", "важно отметить", "стоит отметить", "играет ключевую роль", "в современном мире"];

// Кальки с английского и канцелярит (аудит канала 01.10.2026): [что ищем, чем заменить]
export const CALQUES = [
  [/явля(ется|ются|лся|лась)/, "«является» → просто тире или «это»"],
  [/данн(ый|ая|ое|ые|ого|ой|ом|ых)/, "«данный» → «этот»"],
  [/осуществля/, "«осуществлять» → «делать», «проводить»"],
  [/в рамках/, "«в рамках» → «на», «во время»"],
  [/на сегодняшний день/, "«на сегодняшний день» → «сейчас»"],
  [/в случае,? если/, "«в случае если» → «если»"],
  [/давай(те)? разбер[её]мся/, "«давай разберёмся» — сразу к делу"],
  [/погрузимся|окун[её]мся/, "«погрузимся» — калька с dive into"],
  [/в мире медицины/, "«в мире медицины» — пустая фраза"],
  [/не секрет,? что/, "«не секрет, что» — пустая фраза"],
  [/играет (важную|ключевую|огромную) роль/, "«играет важную роль» — скажите, что именно делает"],
  [/стоит помнить|необходимо помнить|важно помнить/, "«стоит помнить» → «помни» или просто факт"],
  [/подводя итог|в заключение|таким образом/, "«подводя итог / таким образом» — школьное сочинение"],
  [/это не просто/, "«это не просто X, это Y» — штамп из перевода"],
  [/ключ к успеху|золотое правило|настоящий вызов/, "штамп"],
  [/сделать (выбор|вывод) в пользу/, "канцелярит"],
  [/по сути дела|в конечном итоге|в первую очередь стоит/, "канцелярит"],
];

/** Найденные стоп-фразы и кальки в тексте (HTML уже можно не чистить) */
export function styleIssues(text, { calques = true } = {}) {
  const low = String(text).replace(/<[^>]+>/g, " ").toLowerCase().replace(/\s+/g, " ");
  const out = STOP_PHRASES.filter((ph) => low.includes(ph)).map((ph) => `стоп-фраза «${ph}»`);
  // \b в JS не работает с кириллицей — начало слова проверяем сами
  if (calques) for (const [re, hint] of CALQUES) { const m = low.match(new RegExp(`(?<![а-яё])(?:${re.source})`, "u")); if (m) out.push(`«${m[0]}»: ${hint}`); }
  return out;
}
